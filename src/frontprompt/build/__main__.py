"""Canonical build entry: ``python -m frontprompt.build [--wheel]``.

Drives the pipeline documented in ``__init__.py``. Exits 0 on success,
non-zero with a clear error message on failure (missing bun, codegen drift,
vite failure).

By default the pipeline builds the overlay and **embeds** it into the package
tree (``src/frontprompt/_overlay/``) so an installed wheel is self-contained.
With ``--wheel`` it additionally runs ``uv build --wheel`` to produce the
distributable python package in ``dist/``.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import uuid
from datetime import UTC, datetime
from importlib import metadata as _md
from pathlib import Path

_PROJECT_ROOT = Path(__file__).resolve().parents[3]
_FRONTEND_DIR = _PROJECT_ROOT / "frontend"
_GENERATED_DIR = _FRONTEND_DIR / "src" / "_generated"
_DIST_DIR = _FRONTEND_DIR / "dist"
_BUNDLE_PATH = _DIST_DIR / "overlay.iife.js"
_MANIFEST_PATH = _DIST_DIR / "build-manifest.json"

#: Embedded copy inside the package — this is what ships in the wheel and what
#: the loader prefers at runtime (see overlay/loader.py).
_PACKAGE_OVERLAY_DIR = _PROJECT_ROOT / "src" / "frontprompt" / "_overlay"

#: Output dir for the built python package (wheel). Gitignored.
_WHEEL_OUT_DIR = _PROJECT_ROOT / "dist"

_STATE_MODULE = "frontprompt.state.state"
_SCHEMAS_MODULE = "frontprompt.bridge.messages"

#: Mirrors the latest Schema-history entry in CLAUDE.md. Informational only —
#: the bridge build-session handshake keys off the per-build UUID, not this.
_SCHEMA_VERSION = "0.10.0"


def _log(msg: str) -> None:
    print(f"[frontprompt.build] {msg}", file=sys.stderr, flush=True)


def _run_codegen(module: str, output: Path) -> None:
    _log(f"codegen {module} -> {output.relative_to(_PROJECT_ROOT)}")
    output.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        sys.executable,
        "-m",
        "pydantic_zod_codegen.cli",
        "generate",
        module,
        "-o",
        str(output),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        _log(f"codegen failed for {module}:")
        _log(result.stdout)
        _log(result.stderr)
        sys.exit(result.returncode)


def _git_sha() -> str:
    try:
        result = subprocess.run(
            ["git", "-C", str(_PROJECT_ROOT), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=False,
        )
        return result.stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def _project_version() -> str:
    try:
        return _md.version("frontprompt")
    except _md.PackageNotFoundError:
        return "0.0.0"


def _write_build_info(session: str, version: str, sha: str, schema_version: str) -> None:
    target = _GENERATED_DIR / "build-info.ts"
    _log(f"write {target.relative_to(_PROJECT_ROOT)}")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        "// AUTO-GENERATED by `python -m frontprompt.build`. Do not edit.\n"
        f"export const BUILD_SESSION = {json.dumps(session)} as const;\n"
        f"export const BUILD_VERSION = {json.dumps(version)} as const;\n"
        f"export const BUILD_GIT_SHA = {json.dumps(sha)} as const;\n"
        f"export const SCHEMA_VERSION = {json.dumps(schema_version)} as const;\n",
        encoding="utf-8",
    )


def _run_vite(session: str) -> None:
    _log("vite build (bun run build)")
    env = {**os.environ, "FRONTPROMPT_BUILD_SESSION": session}
    # Strip leaked VIRTUAL_ENV (claude-hook-tap class of bug)
    env.pop("VIRTUAL_ENV", None)
    cmd = ["bun", "run", "build"]
    result = subprocess.run(cmd, cwd=_FRONTEND_DIR, env=env)
    if result.returncode != 0:
        _log("vite build failed")
        sys.exit(result.returncode)


def _write_manifest(session: str, version: str, sha: str, schema_version: str) -> None:
    if not _BUNDLE_PATH.is_file():
        _log(f"expected bundle missing after vite build: {_BUNDLE_PATH}")
        sys.exit(1)
    bundle_size = _BUNDLE_PATH.stat().st_size
    payload = {
        "build_session": session,
        "build_version": version,
        "build_git_sha": sha,
        "schema_version": schema_version,
        "generated_at_iso": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "bundle_size_bytes": bundle_size,
        "bundle_path_relative": str(_BUNDLE_PATH.relative_to(_PROJECT_ROOT)),
    }
    _MANIFEST_PATH.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    _log(f"manifest written ({bundle_size} bytes bundle)")


def _embed_into_package() -> None:
    """Copy the vite output into the package tree so the wheel is self-contained.

    The loader prefers ``frontprompt/_overlay/`` over the dev ``frontend/dist``,
    and ``uv_build`` includes everything under the module dir in the wheel
    (gitignored or not), so this single copy makes both the installed-tool and
    dev paths resolve to a present bundle.
    """
    _PACKAGE_OVERLAY_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copy2(_BUNDLE_PATH, _PACKAGE_OVERLAY_DIR / "overlay.iife.js")
    shutil.copy2(_MANIFEST_PATH, _PACKAGE_OVERLAY_DIR / "build-manifest.json")
    _log(f"embedded overlay -> {_PACKAGE_OVERLAY_DIR.relative_to(_PROJECT_ROOT)}/")


def _build_wheel() -> None:
    """Produce the distributable python package (wheel) in ``dist/``.

    The embedded ``_overlay`` is already in place, so the wheel ships the
    frontend. Runs ``uv build --wheel``; chromium is NOT bundled (install it at
    runtime via ``frontprompt bootstrap``).
    """
    _log(f"uv build --wheel -> {_WHEEL_OUT_DIR.relative_to(_PROJECT_ROOT)}/")
    env = {**os.environ}
    env.pop("VIRTUAL_ENV", None)
    cmd = ["uv", "build", "--wheel", "--no-build-logs", "-o", str(_WHEEL_OUT_DIR)]
    result = subprocess.run(cmd, cwd=_PROJECT_ROOT, env=env)
    if result.returncode != 0:
        _log("uv build --wheel failed")
        sys.exit(result.returncode)
    wheels = sorted(_WHEEL_OUT_DIR.glob("*.whl"))
    if wheels:
        _log(f"wheel built: {wheels[-1].relative_to(_PROJECT_ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(
        prog="python -m frontprompt.build",
        description="Build + embed the overlay bundle; optionally package a wheel.",
    )
    parser.add_argument(
        "--wheel",
        action="store_true",
        help="also run `uv build --wheel` to produce the distributable python package in dist/.",
    )
    args = parser.parse_args()

    session = str(uuid.uuid4())
    version = _project_version()
    sha = _git_sha()
    schema_version = _SCHEMA_VERSION

    _log(f"build session {session}")

    _run_codegen(_STATE_MODULE, _GENERATED_DIR / "state.ts")
    _run_codegen(_SCHEMAS_MODULE, _GENERATED_DIR / "schemas.ts")
    _write_build_info(session, version, sha, schema_version)
    _run_vite(session)
    _write_manifest(session, version, sha, schema_version)
    _embed_into_package()

    if args.wheel:
        _build_wheel()

    _log("build complete")


if __name__ == "__main__":
    main()
